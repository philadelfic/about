/**
 * Якоря — контракт с контентом: в «Результатах» ссылки ведут на якоря вида
 * #цикл-агент-среда, поэтому slugify обязан выдавать именно такие строки.
 */
import test from 'node:test';
import assert from 'node:assert/strict';

import { slugify } from '../src/lib/slug.mjs';

test('slugify: кириллица, пунктуация и тире', () => {
  assert.equal(slugify('Цикл «агент — среда»'), 'цикл-агент-среда');
  assert.equal(slugify('Вознаграждение — сигнал, а не цель'), 'вознаграждение-сигнал-а-не-цель');
  assert.equal(slugify('Где можно γ = 1'), 'где-можно-γ-1');
});

test('slugify: греческие буквы и цифры остаются', () => {
  assert.equal(slugify('Доход и дисконтирование'), 'доход-и-дисконтирование');
  assert.equal(slugify('Траектория, эпизод, терминальное состояние'), 'траектория-эпизод-терминальное-состояние');
});

test('slugify: пробелы схлопываются, края чистятся', () => {
  assert.equal(slugify('  Много   пробелов  '), 'много-пробелов');
});

test('slugify: текст без букв — пустая строка (сработает fallback)', () => {
  assert.equal(slugify('!!!'), '');
});
